package tasks

import ContentWarning
import org.gradle.api.DefaultTask
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction

@CacheableTask
abstract class GenerateManifestTask : DefaultTask() {
    @get:Input
    abstract val extensionName: Property<String>

    @get:Input
    abstract val extensionClass: Property<String>

    @get:Input
    abstract val contentWarning: Property<ContentWarning>

    @get:Input
    abstract val extensionLib: Property<String>

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun generate() {
        val name = extensionName.get().escapeXml()
        val clazz = extensionClass.get()
        val lib = extensionLib.get()
        val cw = contentWarning.get()
        val nsfw = if (cw == ContentWarning.SAFE) "0" else "1"
        val cwValue = when (cw) {
            ContentWarning.SAFE -> "0"
            ContentWarning.MIXED -> "1"
            ContentWarning.NSFW -> "2"
        }

        val out = outputFile.get().asFile
        out.parentFile.mkdirs()
        out.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by hikari.plugins.extension — do not edit by hand. -->
            |<manifest xmlns:android="http://schemas.android.com/apk/res/android">
            |    <uses-feature android:name="hikari.extension" />
            |    <application
            |        android:allowBackup="false"
            |        android:icon="@mipmap/ic_launcher"
            |        android:label="Hikari: $name"
            |        android:hasCode="true">
            |        <meta-data android:name="hikari.extension.class" android:value="$clazz" />
            |        <meta-data android:name="hikarix.name" android:value="$name" />
            |        <meta-data android:name="hikari.extension.nsfw" android:value="$nsfw" />
            |        <meta-data android:name="hikarix.contentWarning" android:value="$cwValue" />
            |        <meta-data android:name="hikarix.extensionLib" android:value="$lib" />
            |    </application>
            |</manifest>
            |
            """.trimMargin(),
        )
    }
}

internal fun String.escapeXml() = replace("&", "&amp;")
    .replace("<", "&lt;")
    .replace(">", "&gt;")
    .replace("\"", "&quot;")
    .replace("'", "&apos;")
